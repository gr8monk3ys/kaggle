# ── Cell 7: TextPreprocessor class (code) ─────────────────────────────────────
cells.append(code(
'class TextPreprocessor(BaseEstimator, TransformerMixin):\n'
'    """Sklearn-compatible text cleaning transformer."""\n'
'\n'
'    STOPWORDS = {\n'
'        "the", "a", "an", "in", "on", "at", "to", "for", "of", "and", "or",\n'
'        "is", "are", "was", "were", "that", "this", "it", "with", "as", "be",\n'
'        "by", "from", "up", "about", "into", "through", "during", "has", "have",\n'
'        "had", "do", "does", "did", "will", "would", "could", "should", "may",\n'
'        "might", "not", "no", "its", "their", "our", "your", "his", "her",\n'
'        "we", "they", "he", "she", "you", "i", "my", "but", "if", "then",\n'
'        "than", "so", "yet", "both", "each", "more", "also", "just", "over",\n'
'        "such", "after", "before", "any", "all", "when", "which", "who",\n'
'    }\n'
'\n'
'    def __init__(\n'
'        self,\n'
'        lowercase=True,\n'
'        remove_punctuation=True,\n'
'        remove_numbers=False,\n'
'        remove_stopwords=True,\n'
'    ):\n'
'        self.lowercase = lowercase\n'
'        self.remove_punctuation = remove_punctuation\n'
'        self.remove_numbers = remove_numbers\n'
'        self.remove_stopwords = remove_stopwords\n'
'\n'
'    def _preprocess(self, text):\n'
'        if self.lowercase:\n'
'            text = text.lower()\n'
'        if self.remove_punctuation:\n'
'            text = text.translate(str.maketrans("", "", string.punctuation))\n'
'        if self.remove_numbers:\n'
'            text = re.sub(r"\\d+", "", text)\n'
'        if self.remove_stopwords:\n'
'            tokens = text.split()\n'
'            text = " ".join(t for t in tokens if t not in self.STOPWORDS)\n'
'        return text.strip()\n'
'\n'
'    def fit(self, X, y=None):\n'
'        return self\n'
'\n'
'    def transform(self, X):\n'
'        return [self._preprocess(str(t)) for t in X]\n'
'\n'
'\n'
'# Quick sanity check\n'
'sample = "The AI algorithm achieved state-of-the-art results on 3 benchmarks."\n'
'prep = TextPreprocessor()\n'
'cleaned = prep._preprocess(sample)\n'
'print("Original :", sample)\n'
'print("Cleaned  :", cleaned)'
))

