'## 1. Why Hyperparameter Optimization Matters\n'
'\n'
'### The Cost of Bad Hyperparameters\n'
'\n'
'Machine learning models are extraordinarily sensitive to hyperparameter choices. Consider a gradient-boosted tree:\n'
'\n'
'- **Learning rate**: span of 4 orders of magnitude (0.001 to 1.0)\n'
'- **Max depth**: integer from 2 to 12\n'
'- **Subsample**: continuous from 0.5 to 1.0\n'
'- **colsample_bytree**: continuous from 0.5 to 1.0\n'
'- **reg_alpha, reg_lambda**: log-scale over 6 orders of magnitude each\n'
'\n'
'A naive grid search over just 5 values per parameter = **5^6 = 15,625 evaluations**. At 30 seconds each, that is 130 hours. Kaggle kernels give you 12.\n'
'\n'
'### Comparison of Strategies\n'
'\n'
'| Strategy | Trials to find top-5% params | Wall time (est.) | Handles dependencies? |\n'
'|----------|-------------------------------|------------------|-----------------------|\n'
'| Grid Search | 10,000+ | Days | No |\n'
'| Random Search | 200-500 | Hours | Partially |\n'
'| **Bayesian (Optuna)** | **50-100** | **Minutes** | **Yes** |\n'
'\n'
'### Why Bayesian Optimization Wins\n'
'\n'
'Bayesian optimization maintains a **probabilistic surrogate model** of the objective function. After each trial:\n'
'\n'
'1. The model is updated with the new (params, score) observation\n'
'2. An **acquisition function** (EI -- Expected Improvement) selects the next point to evaluate\n'
'3. Points in promising regions are sampled more frequently\n'
'\n'
'This is fundamentally different from random search: instead of sampling blindly, the algorithm *learns* which regions of the search space are worth exploring.\n'
'\n'
'**Optuna\'s TPE (Tree-structured Parzen Estimator)** extends this to handle:\n'
'- Mixed integer/float/categorical parameters\n'
'- Conditional search spaces (e.g., "only tune dropout if using neural net")\n'
'- Parallel execution across multiple cores or machines\n'
'\n'
