'\n'
'### When to Use CMA-ES\n'
'\n'
'CMA-ES (Covariance Matrix Adaptation Evolution Strategy) is an evolutionary algorithm optimized for **high-dimensional, continuous** search spaces. Use it when:\n'
'\n'
'- Most hyperparameters are **floats** (not integers or categoricals)\n'
