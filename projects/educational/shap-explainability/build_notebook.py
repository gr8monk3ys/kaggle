cells.append(md(
'---\n'
'## 12. Production Tips & Best Practices\n'
'\n'
'### Choosing the Right Explainer\n'
'\n'
'| Situation | Recommended Explainer | Notes |\n'
'|-----------|----------------------|-------|\n'
'| Tree models (XGB, LGB, RF, CatBoost) | `TreeExplainer` | Exact, fast, always use this |\n'
'| Linear models (Ridge, Lasso, LogReg) | `LinearExplainer` | Exact, handles correlations |\n'
'| Any model, debugging/exploration | `KernelExplainer` | Slow, approximate -- sample background |\n'
'| Neural networks | `DeepExplainer` or `KernelExplainer` | DeepExplainer for TensorFlow/Keras |\n'
'\n'
'### Which Plot to Use\n'
'\n'
'| Goal | Plot |\n'
'|------|------|\n'
'| Global feature importance | Summary plot (bar) |\n'
'| Global feature effects + direction | Summary plot (beeswarm) |\n'
'| Single prediction explanation | Waterfall or Force plot |\n'
'| Non-linear effects of a feature | Dependence plot |\n'
'| Feature interactions | Dependence plot with `interaction_index` or Interaction matrix |\n'
'| Production monitoring | Mean absolute SHAP values over time |\n'
'\n'
'### Performance Tips\n'
'\n'
'1. **Always use `TreeExplainer` for tree models** -- it is orders of magnitude faster than KernelExplainer\n'
'2. **Background sample for KernelExplainer**: `shap.sample(X_train, 100)` is usually sufficient\n'
'3. **Batch SHAP computations**: Compute once for a dataset, cache results\n'
'4. **Memory for interaction values**: O(n_samples * n_features^2) -- use < 500 samples\n'
'5. **GPU acceleration**: XGBoost with `device="cuda"` supports fast SHAP on GPU\n'
'\n'
'### Common Pitfalls\n'
'\n'
'| Pitfall | Fix |\n'
'|---------|-----|\n'
'| SHAP values do not sum to prediction | Check `expected_value` -- use `explainer.expected_value`, not 0 |\n'
'| Multi-class SHAP shape confusion | Shape is `(n_samples, n_features, n_classes)` -- index the class |\n'
'| KernelExplainer too slow | Reduce `nsamples`, use smaller background |\n'
'| Interaction values OOM | Reduce sample size, use 32-bit floats |\n'
'| SHAP for probability vs log-odds | Set `model_output="probability"` in TreeExplainer if needed |\n'
'\n'
'### Regulatory & Audit Use Cases\n'
'\n'
'SHAP is widely used for:\n'
'- **Credit scoring explainability** (EU AI Act, GDPR "right to explanation")\n'
'- **Healthcare model auditing** (FDA AI/ML guidelines)\n'
'- **Bias detection** (check if protected features have high SHAP values)\n'
'- **Model debugging** (identify training data artifacts via anomalous SHAP patterns)'
))

