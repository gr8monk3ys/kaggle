# ── Cell 4: Section 1 - What is SHAP? (markdown) ──────────────────────────────
cells.append(md(
'---\n'
'## 1. What is SHAP?\n'
'\n'
'### Game Theory Foundations\n'
'\n'
'SHAP is rooted in **cooperative game theory**. Imagine your model\'s features as players in a '
'coalition game: together they "earn" a prediction (the payout). The question is: how do we '
'fairly credit each player for their contribution?\n'
'\n'
'Lloyd Shapley (Nobel Prize 2012) solved this in 1951. The **Shapley value** of player $i$ is '
'the average marginal contribution of feature $i$ across all possible orderings of features:\n'
'\n'
'$$\\phi_i = \\sum_{S \\subseteq F \\setminus \\{i\\}} \\frac{|S|!(|F|-|S|-1)!}{|F|!} '
'\\left[ f(S \\cup \\{i\\}) - f(S) \\right]$$\n'
'\n'
'Where:\n'
'- $F$ = full set of features\n'
'- $S$ = subset of features not containing $i$\n'
'- $f(S)$ = model output using only features in $S$\n'
'\n'
'### SHAP = SHapley Additive exPlanations\n'
'\n'
'Lundberg & Lee (2017) showed that Shapley values are the **unique** attribution method satisfying '
'three desirable axioms simultaneously:\n'
'\n'
'| Axiom | Meaning |\n'
'|-------|--------|\n'
'| **Local Accuracy** | SHAP values sum exactly to the prediction minus the base value |\n'
'| **Missingness** | Features absent from a sample have zero SHAP value |\n'
'| **Consistency** | If a feature\'s contribution increases in a changed model, its SHAP value does not decrease |\n'
'\n'
'The additive explanation model is:\n'
'\n'
'$$\\hat{f}(x) = \\phi_0 + \\sum_{i=1}^{M} \\phi_i x_i\'$$\n'
'\n'
'Where $\\phi_0 = E[f(x)]$ (the base value / expected model output) and $\\phi_i$ is the SHAP '
'value for feature $i$.\n'
'\n'
'### Why SHAP Beats Naive Feature Importance\n'
'\n'
'| Method | Local? | Consistent? | Handles Correlations? | Speed |\n'
'|--------|--------|-------------|----------------------|-------|\n'
'| Permutation Importance | No (global only) | No | No | Medium |\n'
'| Gain / Impurity Importance | No | No | No | Fast |\n'
'| LIME | Yes | No | Partial | Slow |\n'
'| **SHAP** | **Yes** | **Yes** | **Yes** | **Fast (trees)** |\n'
'\n'
'Standard tree-based feature importance can be misleading for correlated features and gives '
'no information about individual predictions. SHAP provides both local (per-prediction) and '
'global (aggregated) explanations with theoretical guarantees.'
))

